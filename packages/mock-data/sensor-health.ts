// Sensor Health & Data Quality Types
export type HealthStatus = "healthy" | "stale" | "silent";
export type DataQualityStatus = "good" | "missing" | "inconsistent";
export type IngestionSource = "api" | "csv";
export type IngestionStatus = "ok" | "api_error" | "csv_error";
export type QualityWindow = "1h" | "24h" | "7d";
export type ErrorSeverity = "warning" | "alert";

export interface SensorHealthRecord {
	sensorId: string;
	lastReportedAt: string;
	expectedIntervalSeconds: number;
	warningThresholdSeconds: number;
	criticalThresholdSeconds: number;
	healthStatus: HealthStatus;
}

export interface DataQualityRecord {
	sensorId: string;
	window: QualityWindow;
	expectedPoints: number;
	receivedPoints: number;
	missingPoints: number;
	inconsistentPoints: number;
	completenessPct: number;
	consistencyPct: number;
	freshnessPct: number;
	qualityStatus: DataQualityStatus;
	notes?: string;
}

export interface IngestionError {
	id: string;
	sensorId: string;
	timestamp: string;
	source: IngestionSource;
	errorCode: string;
	message: string;
	severity: ErrorSeverity;
}

