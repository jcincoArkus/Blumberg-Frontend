// Helper functions
export function getSensorHealthRecord(sensorId: string): SensorHealthRecord | undefined {
	return sensorHealthRecords.find((r) => r.sensorId === sensorId);
}

export function getDataQualityRecord(
	sensorId: string,
	window: QualityWindow = "24h",
): DataQualityRecord | undefined {
	return dataQualityRecords.find((r) => r.sensorId === sensorId && r.window === window);
}

export function getIngestionErrorsForSensor(
	sensorId: string,
	last24h: boolean = true,
): IngestionError[] {
	const errors = ingestionErrors.filter((e) => e.sensorId === sensorId);
	if (last24h) {
		const cutoff = new Date(Date.now() - 24 * 60 * 60 * 1000);
		return errors.filter((e) => new Date(e.timestamp) >= cutoff);
	}
	return errors;
}

export function getAllIngestionErrorsLast24h(): IngestionError[] {
	const cutoff = new Date(Date.now() - 24 * 60 * 60 * 1000);
	return ingestionErrors.filter((e) => new Date(e.timestamp) >= cutoff);
}

export function getAgeInMinutes(lastReportedAt: string): number {
	const now = Date.now();
	const lastReported = new Date(lastReportedAt).getTime();
	return Math.floor((now - lastReported) / (60 * 1000));
}

export function formatAge(ageMinutes: number): string {
	if (ageMinutes < 60) {
		return `${ageMinutes}m`;
	} else if (ageMinutes < 1440) {
		return `${Math.floor(ageMinutes / 60)}h ${ageMinutes % 60}m`;
	} else {
		return `${Math.floor(ageMinutes / 1440)}d`;
	}
}
